package main

import (
	"strconv"
	"strings"
)

// benchPayload supplies the EchoRequest.message of every request one worker
// sends; see --payload in bench/README.md.
type benchPayload interface {
	// next returns the message of the next request.
	next() string
}

// newBenchPayload returns the payload of worker number worker, from 0.
func newBenchPayload(kind string, size, worker int) benchPayload {
	if kind == "records" {
		return &recordsPayload{state: recordsWorkerSeed + uint64(worker), size: size}
	}
	return repeatPayload(strings.Repeat("x", size))
}

// repeatPayload is the repeat payload: the same size letters x in every
// request.
type repeatPayload string

func (p repeatPayload) next() string { return string(p) }

// recordsWorkerSeed is the generator seed of worker 0; worker i uses it plus
// i.
const recordsWorkerSeed = 0x9E3779B97F4A7C15

// The value lists records draw from, as in bench/payload.py.
var (
	recordServices = []string{"checkout", "cart", "payments", "inventory", "search", "auth", "gateway", "notifier"}
	recordRegions  = []string{"us-east-1", "us-west-2", "eu-west-1", "eu-central-1", "ap-southeast-1"}
	recordMethods  = []string{"GET", "POST", "PUT", "DELETE"}
	recordRoutes   = []string{"/api/v1/orders", "/api/v1/orders/{id}", "/api/v1/cart", "/api/v1/users/{id}", "/api/v1/search", "/healthz"}
	recordStatuses = []uint64{200, 200, 200, 200, 200, 201, 204, 400, 404, 500}
)

// recordsBaseTimestampMS is the ts of the first record, before its jitter.
const recordsBaseTimestampMS = 1_790_000_000_000

// recordsPayload is the records payload of bench/README.md, generated byte for
// byte as bench/payload.py does: every message is new log records, cut to
// size bytes.
type recordsPayload struct {
	state uint64
	// count is the number of records generated so far.
	count uint64
	size  int
	buf   []byte
}

// step advances the xorshift64 state and returns it.
func (p *recordsPayload) step() uint64 {
	x := p.state
	x ^= x << 13
	x ^= x >> 7
	x ^= x << 17
	p.state = x
	return x
}

func (p *recordsPayload) between(low, high uint64) uint64 {
	return low + p.step()%(high-low+1)
}

func (p *recordsPayload) pick(values []string) string {
	return values[p.step()%uint64(len(values))]
}

// appendRecord appends one record line to p.buf.
func (p *recordsPayload) appendRecord() {
	timestamp := recordsBaseTimestampMS + p.count*13 + p.between(0, 12)
	p.count++
	b := append(p.buf, `{"ts":`...)
	b = strconv.AppendUint(b, timestamp, 10)
	b = append(b, `,"service":"`...)
	b = append(b, p.pick(recordServices)...)
	b = append(b, `","region":"`...)
	b = append(b, p.pick(recordRegions)...)
	b = append(b, `","method":"`...)
	b = append(b, p.pick(recordMethods)...)
	b = append(b, `","route":"`...)
	b = append(b, p.pick(recordRoutes)...)
	b = append(b, `","status":`...)
	b = strconv.AppendUint(b, recordStatuses[p.step()%uint64(len(recordStatuses))], 10)
	b = append(b, `,"latency_ms":`...)
	b = strconv.AppendUint(b, p.between(1, 2000), 10)
	b = append(b, `,"trace":"`...)
	for range 32 {
		b = append(b, "0123456789abcdef"[p.step()%16])
	}
	b = append(b, `","user":`...)
	b = strconv.AppendUint(b, p.between(1, 1_000_000), 10)
	p.buf = append(b, "}\n"...)
}

func (p *recordsPayload) next() string {
	p.buf = p.buf[:0]
	for len(p.buf) < p.size {
		p.appendRecord()
	}
	return string(p.buf[:p.size])
}
