use std::error::Error;
use std::io::Write;
use std::path::Path;
use std::process::{Command, Stdio};

use prost::Message;
use prost_types::compiler::{CodeGeneratorRequest, CodeGeneratorResponse};

#[test]
fn generates_services_from_a_real_proto_descriptor() {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let proto_dir = manifest_dir.join("tests/proto");
    let descriptor_set = protox::compile(["greeter.proto"], [&proto_dir]).unwrap();
    let request = CodeGeneratorRequest {
        file_to_generate: vec!["greeter.proto".to_owned()],
        parameter: Some("runtime_path=::trevrpc".to_owned()),
        proto_file: descriptor_set.file,
        compiler_version: None,
    };
    let mut input = Vec::new();
    request.encode(&mut input).unwrap();
    let mut output = Vec::new();

    protoc_gen_trevrpc_rust::run_plugin(input.as_slice(), &mut output).unwrap();

    let response = CodeGeneratorResponse::decode(output.as_slice()).unwrap();
    assert_eq!(response.error, None);
    assert_eq!(response.file.len(), 1);
    assert_eq!(
        response.file[0].name.as_deref(),
        Some("example.greeter.trevrpc.rs")
    );

    let content = response.file[0]
        .content
        .as_deref()
        .expect("plugin should generate content");
    assert!(content.contains("pub trait Greeter"));
    assert!(content.contains("pub struct GreeterClient<T>"));
    assert!(content.contains("pub const SAY_HELLO: &str = \"/example.greeter.Greeter/SayHello\";"));
    assert!(content.contains("async fn say_hello"));
    assert!(content.contains("async fn lots_of_replies"));
    assert!(content.contains("async fn lots_of_greetings"));
    assert!(content.contains("async fn bidi_hello"));
    assert!(content.contains("::trevrpc::client::Call<'_, T,"));
    assert!(content.contains("::trevrpc::client::server_streaming"));
    assert!(content.contains("::trevrpc::client::client_streaming"));
    assert!(content.contains("::trevrpc::client::bidirectional_streaming"));
    assert!(content.contains("server.route_streaming"));
    assert!(content.contains("::trevrpc::RpcKind::ServerStreaming"));
    assert!(content.contains("::trevrpc::RpcKind::ClientStreaming"));
    assert!(content.contains("::trevrpc::RpcKind::BidirectionalStreaming"));

    let buf_config = include_str!("proto/buf.gen.yaml");
    assert!(buf_config.contains("protoc-gen-trevrpc-rust"));

    let checked_in_path = manifest_dir.join("../../examples/shared/greeter.rs");
    let checked_in = std::fs::read_to_string(&checked_in_path).unwrap();
    let formatted = rustfmt_generated(content).unwrap();
    // UPDATE_GENERATED=1 rewrites the generated half of the checked-in bindings, after the
    // hand-written messages.
    if std::env::var_os("UPDATE_GENERATED").is_some() {
        let marker = "// This file is @generated by protoc-gen-trevrpc-rust.";
        let messages = checked_in.split(marker).next().unwrap();
        std::fs::write(&checked_in_path, format!("{messages}{formatted}")).unwrap();
        return;
    }
    assert!(
        checked_in.ends_with(&formatted),
        "checked-in greeter bindings have drifted from generator output"
    );

    compile_generated_service(content).unwrap();
}

fn rustfmt_generated(content: &str) -> Result<String, Box<dyn Error>> {
    let rustfmt = std::env::var_os("RUSTFMT").unwrap_or_else(|| "rustfmt".into());
    let mut child = Command::new(rustfmt)
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()?;
    child
        .stdin
        .take()
        .ok_or("rustfmt stdin should be piped")?
        .write_all(content.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        return Err("rustfmt should format generated code".into());
    }
    Ok(String::from_utf8(output.stdout)?)
}

#[allow(clippy::too_many_lines)]
fn compile_generated_service(content: &str) -> Result<(), Box<dyn Error>> {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let workspace_root = manifest_dir.join("../..").canonicalize()?;
    let temp_dir =
        std::env::temp_dir().join(format!("trevrpc-generated-compile-{}", std::process::id()));

    if temp_dir.exists() {
        std::fs::remove_dir_all(&temp_dir)?;
    }

    std::fs::create_dir_all(temp_dir.join("src"))?;
    std::fs::write(temp_dir.join("src/generated.rs"), content)?;
    std::fs::write(
        temp_dir.join("Cargo.toml"),
        format!(
            r#"[package]
name = "trevrpc-generated-compile"
version = "0.1.0"
edition = "2024"

[dependencies]
futures-util = "0.3"
prost = "0.14.4"
trevrpc = {{ path = "{}" }}
"#,
            workspace_root.display()
        ),
    )?;
    std::fs::write(
        temp_dir.join("src/lib.rs"),
        r#"use futures_util::StreamExt;

#[derive(Clone, PartialEq, prost::Message)]
pub struct HelloRequest {
    #[prost(string, tag = "1")]
    pub name: String,
}

#[derive(Clone, PartialEq, prost::Message)]
pub struct HelloReply {
    #[prost(string, tag = "1")]
    pub message: String,
}

include!("generated.rs");

struct Service;

#[trevrpc::async_trait]
impl Greeter for Service {
    async fn say_hello(
        &self,
        _context: trevrpc::server::RequestContext,
        request: HelloRequest,
    ) -> core::result::Result<HelloReply, trevrpc::Status> {
        Ok(HelloReply { message: request.name })
    }

    async fn lots_of_replies(
        &self,
        _context: trevrpc::server::RequestContext,
        request: HelloRequest,
    ) -> core::result::Result<trevrpc::BoxStream<HelloReply>, trevrpc::Status> {
        Ok(trevrpc::stream::from_iter([HelloReply {
            message: request.name,
        }]))
    }

    async fn lots_of_greetings(
        &self,
        _context: trevrpc::server::RequestContext,
        mut requests: trevrpc::BoxStream<HelloRequest>,
    ) -> core::result::Result<HelloReply, trevrpc::Status> {
        let mut names = Vec::new();

        while let Some(request) = requests.next().await {
            names.push(request?.name);
        }

        Ok(HelloReply {
            message: names.join(","),
        })
    }

    async fn bidi_hello(
        &self,
        _context: trevrpc::server::RequestContext,
        requests: trevrpc::BoxStream<HelloRequest>,
    ) -> core::result::Result<trevrpc::BoxStream<HelloReply>, trevrpc::Status> {
        Ok(Box::pin(requests.map(|request| {
            request.map(|request| HelloReply {
                message: request.name,
            })
        })))
    }
}

pub fn register(server: &mut trevrpc::server::Server) {
    register_greeter(server, Service);
}

fn require_send<F: Send>(future: F) -> F {
    future
}

/// Makes every shape of call the generated client offers, which only has to compile.
pub async fn call<T>(client: &GreeterClient<T>) -> trevrpc::Result<()>
where
    T: trevrpc::client::StreamingRpcTransport,
{
    use std::future::IntoFuture as _;

    let request = HelloRequest {
        name: "a".to_owned(),
    };
    let requests = || trevrpc::stream::from_iter([request.clone()]);
    let _reply: HelloReply = require_send(
        client
            .say_hello(&request)
            .timeout(std::time::Duration::from_secs(1))
            .into_future(),
    )
    .await?;
    let _envelope = client.say_hello(&request).with_response().await?;
    let _replies = client.lots_of_replies(&request).metadata("k", "v").await?;
    let _upload = client.lots_of_greetings().await?;
    let _reply: HelloReply = client.lots_of_greetings().send_all(requests()).await?;
    let _envelope = client
        .lots_of_greetings()
        .send_all(requests())
        .with_response()
        .await?;
    let _call = client
        .bidi_hello()
        .options(|options| options.with_max_response_messages(Some(1)))
        .await?;
    let _replies = client.bidi_hello().send_all(requests()).await?;
    Ok(())
}
"#,
    )?;

    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let status = Command::new(cargo)
        .arg("check")
        .arg("--quiet")
        .arg("--offline")
        .current_dir(&temp_dir)
        .env("CARGO_TARGET_DIR", temp_dir.join("target"))
        .status()?;

    if !status.success() {
        return Err("generated service crate should compile".into());
    }
    std::fs::remove_dir_all(temp_dir)?;

    Ok(())
}
