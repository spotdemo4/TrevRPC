%% @doc The module of a service.
%%
%% Each service gets a module of its own (see
%% {@link trevrpc_gen_names:service_module/3}) with:
%%
%% - a behaviour, one callback per method, for the module that handles the
%%   service;
%% - `routes/1', the service's routes for `trevrpc_server', with handlers
%%   from a module that implements the behaviour or from a map of funs, and
%%   each method's message types, compression and codec;
%% - per method, a function that calls it on a `trevrpc_channel', with and
%%   without call options.
%%
%% Messages are those of the gpb module of the service's proto file, which
%% the codecs encode and decode with.
-module(trevrpc_gen_service).

-export([check/2, generate/2]).

-export_type([context/0]).

%% What a service module is generated from: its proto file and service,
%% its module and that of its file's messages, the message format, and
%% every message of the request, for the fields marked `debug_redact'.
-type context() :: #{
    file := trevrpc_gen_descriptor:file(),
    service := trevrpc_gen_descriptor:service(),
    module := binary(),
    messages_module := binary(),
    format := trevrpc_gen_messages:format(),
    messages := #{binary() => trevrpc_gen_descriptor:message()}
}.

-define(UNSPECIFIED, 0).
-define(MESSAGE, 1).
-define(STREAM, 2).

%% The functions of a service module that its methods' cannot be named
%% after.
-define(RESERVED, [<<"routes">>, <<"module_info">>, <<"behaviour_info">>]).

%% @doc Checks that a service's methods have distinct function names, none
%% of them taken, and options that apply to them.
-spec check(binary(), trevrpc_gen_descriptor:service()) -> ok | {error, binary()}.
check(Package, #{name := Service, methods := Methods}) ->
    Full = qualified(Package, Service),
    Named = [{trevrpc_gen_names:snake(Name), Name} || #{name := Name} <- Methods],
    Errors =
        [
            format("service ~ts RPC methods ~ts and ~ts both require generated function ~ts", [
                Full, First, Second, Snake
            ])
         || {Snake, First} <- Named,
            {S, Second} <- Named,
            S =:= Snake,
            First < Second
        ] ++
            [
                format(
                    "service ~ts RPC method ~ts requires generated function ~ts, which is taken", [
                        Full, Name, Snake
                    ]
                )
             || {Snake, Name} <- Named, lists:member(Snake, ?RESERVED)
            ] ++
            lists:append([method_errors(Full, Method) || Method <- Methods]),
    case Errors of
        [] -> ok;
        [Error | _] -> {error, Error}
    end.

method_errors(Service, #{name := Name} = Method) ->
    #{
        client_streaming := Requests,
        server_streaming := Responses,
        compression := Compression,
        unreliable_requests := UnreliableRequests,
        unreliable_responses := UnreliableResponses
    } = Method,
    Full = <<Service/binary, ".", Name/binary>>,
    [
        format("~ts: COMPRESSION_STREAM requires a streaming method", [Full])
     || Compression =:= ?STREAM, not Requests, not Responses
    ] ++
        [
            format("~ts: unknown compression ~b", [Full, Compression])
         || Compression > ?STREAM
        ] ++
        [
            format(
                "~ts: unreliable_requests requires a client-streaming or bidirectional method",
                [Full]
            )
         || UnreliableRequests, not Requests
        ] ++
        [
            format(
                "~ts: unreliable_responses requires a server-streaming or bidirectional method",
                [Full]
            )
         || UnreliableResponses, not Responses
        ].

%% @doc The source of a service module.
-spec generate(binary(), context()) -> iodata().
generate(Source, #{file := #{package := Package}, service := Service, module := Module} = Context) ->
    #{name := Name, methods := Methods} = Service,
    Full = qualified(Package, Name),
    [
        "%% Code generated by protoc-gen-trevrpc-erlang. DO NOT EDIT.\n"
        "%% Source: ",
        Source,
        "\n\n"
        "%% @doc The `",
        Full,
        "' service: the behaviour of a module that\n"
        "%% handles it, its routes for `trevrpc_server', and a function per method\n"
        "%% that calls it on a `trevrpc_channel'.\n"
        "-module(",
        trevrpc_gen_names:atom(Module),
        ").\n",
        include(Context),
        "\n-export([routes/1]).\n",
        exports(Methods),
        "\n-export_type([handlers/0]).\n",
        [callback(Context, Method) || Method <- Methods],
        handlers_type(Context, Methods),
        routes(Context, Full, Methods),
        [client(Context, Full, Method) || Method <- Methods]
    ].

include(#{format := maps}) ->
    [];
include(#{format := records, messages_module := Messages}) ->
    ["-include(\"", Messages, ".hrl\").\n"].

exports([]) ->
    [];
exports(Methods) ->
    Functions = lists:append([
        [[function(Method), "/", integer_to_list(Arity)] || Arity <- arities(Method)]
     || Method <- Methods
    ]),
    ["-export([\n", lists:join(",\n", [["    ", F] || F <- Functions]), "\n]).\n"].

%% A client function takes the channel and, unless the client streams, the
%% request, then optionally the call's options.
arities(#{client_streaming := true}) -> [1, 2];
arities(#{client_streaming := false}) -> [2, 3].

function(#{name := Name}) ->
    trevrpc_gen_names:atom(trevrpc_gen_names:snake(Name)).

callback(Context, Method) ->
    [
        "\n-callback ",
        function(Method),
        "(",
        lists:join(", ", handler_args(Context, Method)),
        ") ->\n    ",
        handler_result(Context, Method),
        ".\n"
    ].

handler_args(Context, #{client_streaming := false, input := Input}) ->
    [type(Context, Input), "trevrpc_call:call()"];
handler_args(_Context, #{client_streaming := true}) ->
    ["trevrpc_call:call()"].

handler_result(Context, #{server_streaming := false, output := Output}) ->
    ["{ok, ", type(Context, Output), "} | {error, trevrpc_status:status()}"];
handler_result(_Context, #{server_streaming := true}) ->
    "ok | {error, trevrpc_status:status()}".

type(#{format := maps, messages_module := Messages}, Name) ->
    [trevrpc_gen_names:atom(Messages), ":", trevrpc_gen_names:atom(Name), "()"];
type(#{format := records}, Name) ->
    ["#", trevrpc_gen_names:atom(Name), "{}"].

handlers_type(_Context, []) ->
    "\n%% A module that implements the behaviour.\n-type handlers() :: module() | #{}.\n";
handlers_type(Context, Methods) ->
    [
        "\n%% A module that implements the behaviour, or handler funs by method name.\n"
        "-type handlers() ::\n"
        "    module()\n"
        "    | #{\n",
        lists:join(",\n", [
            [
                "        ",
                function(Method),
                " => fun(\n            (",
                lists:join(", ", handler_args(Context, Method)),
                ") ->\n                ",
                handler_result(Context, Method),
                "\n        )"
            ]
         || Method <- Methods
        ]),
        "\n    }.\n"
    ].

routes(_Context, _Service, []) ->
    [
        "\n%% @doc The service's routes, for `trevrpc_server': none, as it has no\n"
        "%% methods. A handler in the map fails with `{unknown_method, Name, []}'.\n"
        "-spec routes(handlers()) -> trevrpc_server:routes().\n"
        "routes(Module) when is_atom(Module) ->\n"
        "    #{};\n"
        "routes(Handlers) when is_map(Handlers) ->\n"
        "    maps:foreach(fun(Name, _) -> erlang:error({unknown_method, Name, []}) end, Handlers),\n"
        "    #{}.\n"
    ];
routes(Context, Service, Methods) ->
    [
        "\n%% @doc The service's routes, for the `routes' of `trevrpc_server'.\n"
        "%% `Handlers' is a module that implements the behaviour, or a map of\n"
        "%% handler funs by method name; a method missing from the map is not\n"
        "%% routed, and calls to it fail as `unimplemented'. A name that is no\n"
        "%% method fails with `{unknown_method, Name, Methods}'.\n"
        "-spec routes(handlers()) -> trevrpc_server:routes().\n"
        "routes(Module) when is_atom(Module) ->\n"
        "    routes(#{\n",
        lists:join(",\n", [
            [
                "        ",
                function(Method),
                " => fun Module:",
                function(Method),
                "/",
                integer_to_list(handler_arity(Method))
            ]
         || Method <- Methods
        ]),
        "\n    });\n"
        "routes(Handlers) when is_map(Handlers) ->\n"
        "    Routes = #{\n",
        lists:join(",\n", [route(Context, Service, Method) || Method <- Methods]),
        "\n    },\n"
        "    maps:from_list([\n"
        "        case Routes of\n"
        "            #{Name := {Path, Route}} ->\n"
        "                {Path, Route#{handler => Handler}};\n"
        "            #{} ->\n"
        "                erlang:error({unknown_method, Name, lists:sort(maps:keys(Routes))})\n"
        "        end\n"
        "     || Name := Handler <- Handlers\n"
        "    ]).\n"
    ].

handler_arity(#{client_streaming := true}) -> 1;
handler_arity(#{client_streaming := false}) -> 2.

route(Context, Service, #{input := Input, output := Output} = Method) ->
    [
        "        ",
        function(Method),
        " =>\n            {",
        path(Service, Method),
        ", #{\n",
        lists:join(",\n", [
            ["                ", Field]
         || Field <- [
                ["kind => ", kind(Method)]
                | schema_options(Context, Method, {Input, decode}, {Output, encode})
            ]
        ]),
        "\n            }}"
    ].

client(Context, Service, #{input := Input, output := Output} = Method) ->
    Path = path(Service, Method),
    Schema = [
        "    Schema = #{\n",
        lists:join(",\n", [
            ["        ", Field]
         || Field <- schema_options(Context, Method, {Input, encode}, {Output, decode})
        ]),
        "\n    },\n"
    ],
    #{name := Name} = Method,
    F = function(Method),
    case Method of
        #{client_streaming := false} ->
            Call =
                case Method of
                    #{server_streaming := false} -> "unary";
                    #{server_streaming := true} -> "server_stream"
                end,
            Result = client_result(Context, Method),
            [
                "\n%% @doc Calls ",
                Name,
                " with no call options.\n"
                "-spec ",
                F,
                "(pid(), ",
                type(Context, Input),
                ") ->\n    ",
                Result,
                ".\n",
                F,
                "(Channel, Request) ->\n    ",
                F,
                "(Channel, Request, #{}).\n"
                "\n%% @doc Calls ",
                Name,
                "; see `trevrpc_client:",
                Call,
                "/4' for `Options'.\n"
                "-spec ",
                F,
                "(pid(), ",
                type(Context, Input),
                ", trevrpc_client:options()) ->\n    ",
                Result,
                ".\n",
                F,
                "(Channel, Request, Options) ->\n",
                Schema,
                "    trevrpc_client:",
                Call,
                "(Channel, ",
                Path,
                ", Request, maps:merge(Schema, Options)).\n"
            ];
        #{client_streaming := true} ->
            Call =
                case Method of
                    #{server_streaming := false} -> "client_stream";
                    #{server_streaming := true} -> "bidi"
                end,
            Result = "{ok, trevrpc_client:call()} | {error, trevrpc_status:status()}",
            [
                "\n%% @doc Starts a call to ",
                Name,
                " with no call options.\n"
                "-spec ",
                F,
                "(pid()) -> ",
                Result,
                ".\n",
                F,
                "(Channel) ->\n    ",
                F,
                "(Channel, #{}).\n"
                "\n%% @doc Starts a call to ",
                Name,
                "; see `trevrpc_client:",
                Call,
                "/3' for `Options'.\n"
                "-spec ",
                F,
                "(pid(), trevrpc_client:options()) ->\n    ",
                Result,
                ".\n",
                F,
                "(Channel, Options) ->\n",
                Schema,
                "    trevrpc_client:",
                Call,
                "(Channel, ",
                Path,
                ", maps:merge(Schema, Options)).\n"
            ]
    end.

client_result(Context, #{server_streaming := false, output := Output}) ->
    [
        "{ok, ",
        type(Context, Output),
        ", #{\n"
        "        headers := trevrpc_metadata:metadata(), trailers := trevrpc_metadata:metadata()\n"
        "    }}\n"
        "    | {error, trevrpc_status:status()}"
    ];
client_result(_Context, #{server_streaming := true}) ->
    "{ok, trevrpc_client:call()} | {error, trevrpc_status:status()}".

%% The options a method's schema gives its routes and calls: its message
%% types, how its messages may be compressed, and its codec, which encodes
%% one side's messages and decodes the other's.
schema_options(Context, Method, {Input, InputOp}, {Output, OutputOp}) ->
    #{messages_module := Messages} = Context,
    Mod = trevrpc_gen_names:atom(Messages),
    Codec = fun(Op, Type) ->
        case Op of
            encode ->
                [
                    "encode => fun(Message) -> ",
                    Mod,
                    ":encode_msg(Message, ",
                    trevrpc_gen_names:atom(Type),
                    ") end"
                ];
            decode ->
                [
                    "decode => fun(Bin) -> ",
                    Mod,
                    ":decode_msg(Bin, ",
                    trevrpc_gen_names:atom(Type),
                    ") end"
                ]
        end
    end,
    Ops = lists:sort([{InputOp, Input}, {OutputOp, Output}]),
    Indent =
        case InputOp of
            decode -> "                ";
            encode -> "        "
        end,
    [
        ["request_type => <<\"", Input, "\">>"],
        ["response_type => <<\"", Output, "\">>"]
    ] ++
        compression(Context, Method) ++
        [
            [
                "codec => #{\n",
                lists:join(",\n", [[Indent, "    ", Codec(Op, Type)] || {Op, Type} <- Ops]),
                "\n",
                Indent,
                "}"
            ]
        ].

%% How a method's messages may be compressed without a dictionary, as
%% `trevrpc_zstd:directions()': not at all without COMPRESSION_MESSAGE or
%% COMPRESSION_STREAM, never for a side whose message type has a field
%% marked `debug_redact', and with a context per call only for a side that
%% streams.
compression(#{messages := Messages}, Method) ->
    #{
        compression := Compression,
        input := Input,
        output := Output,
        client_streaming := StreamsRequests,
        server_streaming := StreamsResponses
    } = Method,
    Mode = fun(Type, Streams) ->
        case redacted(Type, Messages, #{}) of
            true -> none;
            false when Compression =:= ?STREAM, Streams -> stream;
            false when Compression =/= ?UNSPECIFIED -> message;
            false -> none
        end
    end,
    case {Mode(Input, StreamsRequests), Mode(Output, StreamsResponses)} of
        {none, none} ->
            [];
        {Same, Same} ->
            [["compression => ", atom_to_list(Same)]];
        {Requests, Responses} ->
            [
                [
                    "compression => #{requests => ",
                    atom_to_list(Requests),
                    ", responses => ",
                    atom_to_list(Responses),
                    "}"
                ]
            ]
    end.

%% Whether message type `Name' has a field marked `debug_redact', itself or
%% in a message type it contains; `Seen' ends recursive types.
redacted(Name, _Messages, Seen) when is_map_key(Name, Seen) ->
    false;
redacted(Name, Messages, Seen) ->
    case Messages of
        #{Name := #{fields := Fields}} ->
            lists:any(
                fun
                    (#{debug_redact := true}) -> true;
                    (#{type_name := undefined}) -> false;
                    (#{type_name := Type}) -> redacted(Type, Messages, Seen#{Name => true})
                end,
                Fields
            );
        #{} ->
            false
    end.

kind(#{client_streaming := false, server_streaming := false}) -> "unary";
kind(#{client_streaming := true, server_streaming := false}) -> "client_streaming";
kind(#{client_streaming := false, server_streaming := true}) -> "server_streaming";
kind(#{client_streaming := true, server_streaming := true}) -> "bidirectional_streaming".

%% The method path, `/package.Service/Method', as a binary literal.
path(Service, #{name := Name}) ->
    ["<<\"/", Service, "/", Name, "\">>"].

qualified(<<>>, Name) -> Name;
qualified(Package, Name) -> <<Package/binary, ".", Name/binary>>.

format(Format, Args) ->
    unicode:characters_to_binary(io_lib:format(Format, Args)).
