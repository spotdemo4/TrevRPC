%% @doc protoc-gen-trevrpc-gleam's service modules, over the Gleam binding.
%%
%% Each service of `example/v1/greeter.proto' gets a module of its own
%% beside the file's, `example/v1/greeter_trevrpc.gleam' for a service
%% `Greeter', with:
%%
%% - per method, `say_hello_method()': its `schema.Method', with its path,
%%   the codecs of its messages from their modules, and what its
%%   `trevrpc.method' option allows (compression, as the Erlang plugin
%%   decides it, and datagrams);
%% - `Handlers', a record of a handler function per method, and
%%   `routes(handlers)', the service's routes for `server.Config';
%% - per method, a function that calls it on a channel.
-module(trevrpc_gen_gleam_service).

-export([module_path/2, generate/3]).

%% @doc The path of a service's Gleam module, without `.gleam': beside its
%% proto file's, named after the service.
-spec module_path(binary(), binary()) -> binary().
module_path(Dir, Service) ->
    <<Dir/binary, (trevrpc_gen_names:snake(Service))/binary, "_trevrpc">>.

%% @doc The source of a service's module, or why it cannot be generated.
-spec generate(binary(), trevrpc_gen_descriptor:service(), map()) ->
    {ok, iodata()} | {error, binary()}.
generate(Source, #{name := Name, methods := Methods}, #{package := Package} = Context) ->
    Full = trevrpc_gen_names:qualified(Package, Name),
    maybe
        ok ?= names(Full, Methods),
        Body = [
            [method(Full, Method, Context) || Method <- Methods],
            handlers(Methods, Context),
            routes(Methods),
            [client(Method, Context) || Method <- Methods]
        ],
        {ok, [
            "//// Generated by protoc-gen-trevrpc-gleam from ",
            Source,
            ". Do not edit.\n////\n//// The `",
            Full,
            "` service: a route per method for `trevrpc/server`, and a\n"
            "//// function per method that calls it on a `trevrpc/channel`.\n\n",
            imports(Methods, Context),
            Body
        ]}
    end.

%% Each method's functions and handler label, which must be distinct.
names(Full, Methods) ->
    Functions = lists:append([
        [label(Method), <<(snake(Method))/binary, "_method">>]
     || Method <- Methods
    ]),
    case [F || F <- Functions, F =:= <<"routes">>] ++ (Functions -- lists:usort(Functions)) of
        [] ->
            ok;
        [Function | _] ->
            trevrpc_gen_errors:new("service ~ts: two Gleam functions are named ~ts", [
                Full, Function
            ])
    end.

snake(#{name := Name}) -> trevrpc_gen_names:snake(Name).

label(#{name := Name}) -> trevrpc_gen_gleam:label(Name).

%% The modules of the methods' messages, and the Gleam binding's.
imports(Methods, #{modules := Modules, owners := Owners}) ->
    Keys = lists:usort([
        maps:get(binary_to_atom(Type), Owners)
     || #{input := Input, output := Output} <- Methods, Type <- [Input, Output]
    ]),
    Messages = [
        begin
            #{path := Path, last := Last} = maps:get(Key, Modules),
            case trevrpc_gen_gleam:alias(Key, Modules) of
                Last -> <<"import ", Path/binary, "\n">>;
                Alias -> <<"import ", Path/binary, " as ", Alias/binary, "\n">>
            end
        end
     || Key <- Keys
    ],
    [
        lists:sort(
            Messages ++
                [
                    <<"import trevrpc/channel.{type Channel}\n">>,
                    <<"import trevrpc/client\n">>,
                    <<"import trevrpc/handler\n">>,
                    <<"import trevrpc/schema\n">>,
                    <<"import trevrpc/server\n">>,
                    <<"import trevrpc/status.{type Status}\n">>
                ]
        ),
        "\n"
    ].

%% A message's type, and the names of its encoder and decoder, qualified
%% with its module's alias.
message(Type, #{modules := Modules, owners := Owners} = Context) ->
    Name = binary_to_atom(Type),
    Alias = trevrpc_gen_gleam:alias(maps:get(Name, Owners), Modules),
    Gleam = trevrpc_gen_gleam:type_name_of(Name, Context),
    Snake = trevrpc_gen_gleam:gleam_snake(Gleam),
    #{
        type => [Alias, ".", Gleam],
        encode => [Alias, ".encode_", Snake],
        decode => [Alias, ".decode_", Snake]
    }.

method(Full, #{name := Name, input := Input, output := Output} = Method, Context) ->
    #{type := InType, encode := InEncode, decode := InDecode} = message(Input, Context),
    #{type := OutType, encode := OutEncode, decode := OutDecode} = message(Output, Context),
    {RequestMode, ResponseMode} = trevrpc_gen_service:modes(
        maps:get(descriptor_messages, Context), Method
    ),
    Unreliable = trevrpc_gen_service:unreliable(Method),
    [
        "/// `",
        Full,
        ".",
        Name,
        "`, as `trevrpc/schema` describes it.\npub fn ",
        snake(Method),
        "_method() -> schema.Method(",
        InType,
        ", ",
        OutType,
        ") {\n  schema.Method(\n"
        "    path: \"/",
        Full,
        "/",
        Name,
        "\",\n    request: schema.Codec(encode: ",
        InEncode,
        ", decode: ",
        InDecode,
        "),\n    response: schema.Codec(encode: ",
        OutEncode,
        ", decode: ",
        OutDecode,
        "),\n    request_type: \"",
        Input,
        "\",\n    response_type: \"",
        Output,
        "\",\n    request_compression: ",
        mode(RequestMode),
        ",\n    response_compression: ",
        mode(ResponseMode),
        ",\n    unreliable_requests: ",
        bool(lists:member(requests, Unreliable)),
        ",\n    unreliable_responses: ",
        bool(lists:member(responses, Unreliable)),
        ",\n  )\n}\n\n"
    ].

mode(none) -> <<"schema.NoCompression">>;
mode(message) -> <<"schema.MessageCompression">>;
mode(stream) -> <<"schema.StreamCompression">>.

bool(true) -> <<"True">>;
bool(false) -> <<"False">>.

handlers([], _Context) ->
    [];
handlers(Methods, Context) ->
    [
        "/// A handler per method of the service.\npub type Handlers {\n  Handlers(\n",
        [["    ", label(Method), ": ", handler_type(Method, Context), ",\n"] || Method <- Methods],
        "  )\n}\n\n"
    ].

handler_type(#{input := Input, output := Output} = Method, Context) ->
    #{type := In} = message(Input, Context),
    #{type := Out} = message(Output, Context),
    Call = ["handler.Call(", In, ", ", Out, ")"],
    Arguments =
        case Method of
            #{client_streaming := false} -> [In, ", ", Call];
            #{client_streaming := true} -> Call
        end,
    Result =
        case Method of
            #{server_streaming := false} -> Out;
            #{server_streaming := true} -> "Nil"
        end,
    ["fn(", Arguments, ") -> Result(", Result, ", Status)"].

routes(Methods) ->
    [
        "/// The service's routes, for `server.Config`.\n"
        "pub fn routes(handlers: Handlers) -> List(server.Route) {\n  [\n",
        [
            [
                "    server.",
                route(Method),
                "(",
                snake(Method),
                "_method(), handlers.",
                label(Method),
                "),\n"
            ]
         || Method <- Methods
        ],
        "  ]\n}\n\n"
    ].

%% The `trevrpc/server' function that makes a method's route, after its
%% kind as the Erlang plugin decides it.
route(Method) ->
    case trevrpc_gen_service:kind(Method) of
        unary -> "unary";
        server_streaming -> "server_streaming";
        client_streaming -> "client_streaming";
        bidirectional_streaming -> "bidi"
    end.

client(#{name := Name, input := Input, output := Output} = Method, Context) ->
    #{type := In} = message(Input, Context),
    #{type := Out} = message(Output, Context),
    {Parameters, Arguments, Result, Function} =
        case Method of
            #{client_streaming := false, server_streaming := false} ->
                {[", request: ", In], ", request", ["client.Reply(", Out, ")"], "unary"};
            #{client_streaming := false, server_streaming := true} ->
                {
                    [", request: ", In],
                    ", request",
                    ["client.Call(", In, ", ", Out, ")"],
                    "server_stream"
                };
            #{client_streaming := true, server_streaming := false} ->
                {[], "", ["client.Call(", In, ", ", Out, ")"], "client_stream"};
            #{client_streaming := true, server_streaming := true} ->
                {[], "", ["client.Call(", In, ", ", Out, ")"], "bidi"}
        end,
    [
        "/// Calls `",
        Name,
        "`.\npub fn ",
        label(Method),
        "(\n  channel: Channel",
        Parameters,
        ",\n  options: client.Options,\n) -> Result(",
        Result,
        ", Status) {\n  client.",
        Function,
        "(channel, ",
        snake(Method),
        "_method()",
        Arguments,
        ", options)\n}\n\n"
    ].
