import { fromBinary } from "@bufbuild/protobuf";
import { BinaryReader, WireType } from "@bufbuild/protobuf/wire";

export const Code = Object.freeze({
  Ok: 0,
  Cancelled: 1,
  Unknown: 2,
  InvalidArgument: 3,
  DeadlineExceeded: 4,
  NotFound: 5,
  AlreadyExists: 6,
  PermissionDenied: 7,
  ResourceExhausted: 8,
  FailedPrecondition: 9,
  Aborted: 10,
  OutOfRange: 11,
  Unimplemented: 12,
  Internal: 13,
  Unavailable: 14,
  DataLoss: 15,
  Unauthenticated: 16,
});

const CodeNames = Object.freeze(Object.keys(Code));

/** Error carrying a TrevRPC status code, message, metadata, and details. */
export class TrevRpcError extends Error {
  /** Creates a TrevRPC status error. */
  constructor(code, message = "", metadata = {}, options = {}) {
    const normalizedCode = codeFromNumber(code);
    const name = codeName(normalizedCode);
    super(
      message === "" ? name : `${name}: ${message}`,
      options.cause === undefined ? undefined : { cause: options.cause },
    );
    this.name = "TrevRpcError";
    this.code = normalizedCode;
    this.statusMessage = message;
    this.metadata = metadata;
    this.details = options.details ?? [];
  }

  /**
   * Decodes the details whose type is the full name of `schema`, a message schema generated by
   * protoc-gen-es, such as `ViolationsSchema` for `buf.validate.Violations`.
   */
  findDetails(schema) {
    return this.details
      .filter((detail) => detail.type === schema.typeName)
      .map((detail) => fromBinary(schema, detail.value));
  }
}

/** The full name of google.rpc.RetryInfo, the standard detail that tells a client when to retry. */
const RETRY_INFO_TYPE = "google.rpc.RetryInfo";

/**
 * How long the status tells the client to wait before it retries, in milliseconds, from its first
 * well-formed google.rpc.RetryInfo detail, such as that of a call a server's rate limit rejected;
 * `undefined` when it has none. A detail that does not decode, or whose delay is negative or not a
 * valid google.protobuf.Duration, is ignored. The delay can have a fraction of a millisecond.
 */
Object.defineProperty(TrevRpcError.prototype, "retryDelayMs", {
  get() {
    for (const detail of this.details) {
      if (detail.type === RETRY_INFO_TYPE) {
        const delay = decodeRetryInfo(detail.value);
        if (delay !== undefined) {
          return delay;
        }
      }
    }
    return undefined;
  },
});

/**
 * Decodes a google.rpc.RetryInfo into its delay in milliseconds. TrevRPC does this itself, so that
 * it does not depend on googleapis. Returns `undefined` when the message is malformed, has no
 * retry_delay, or holds a delay that is not a valid non-negative Duration: its nanos must be below
 * a second. Fields it does not know are skipped, and a repeated field takes its last value, as
 * protobuf decoders do.
 */
function decodeRetryInfo(value) {
  let duration;
  let seconds = 0n;
  let nanos = 0;
  try {
    for (const reader = new BinaryReader(value); reader.pos < reader.len;) {
      const [field, wireType] = reader.tag();
      if (field === 1) {
        duration = lengthDelimited(reader, wireType);
      } else {
        reader.skip(wireType);
      }
    }
    if (duration === undefined) {
      return undefined;
    }
    for (const reader = new BinaryReader(duration); reader.pos < reader.len;) {
      const [field, wireType] = reader.tag();
      if (field !== 1 && field !== 2) {
        reader.skip(wireType);
      } else if (wireType !== WireType.Varint) {
        return undefined;
      } else if (field === 1) {
        seconds = BigInt(reader.int64());
      } else {
        nanos = reader.int32();
      }
    }
  } catch {
    return undefined;
  }
  if (seconds < 0n || nanos < 0 || nanos >= 1_000_000_000) {
    return undefined;
  }
  return Number(seconds) * 1000 + nanos / 1e6;
}

/** Reads the bytes of a length-delimited field, or throws when the field has another wire type. */
function lengthDelimited(reader, wireType) {
  if (wireType !== WireType.LengthDelimited) {
    throw new Error("unexpected wire type");
  }
  return reader.bytes();
}

// A discriminant for libraries that match errors by tag, such as Effect's `catchTag`. It is on the
// prototype, so errors carry no extra own property.
Object.defineProperty(TrevRpcError.prototype, "_tag", { value: "TrevRpcError" });

/** Converts a number into a known status code, defaulting unknown values to Unknown. */
function codeFromNumber(code) {
  return Number.isInteger(code) && code >= 0 && code < CodeNames.length ? code : Code.Unknown;
}

/** Returns the canonical status code name. */
export function codeName(code) {
  return CodeNames[codeFromNumber(code)];
}

/** Creates a TrevRPC status error. */
export function statusError(code, message = "", metadata = {}, cause, details) {
  return new TrevRpcError(code, message, metadata, { cause, details });
}

/** Creates an internal error status. */
export function internal(message) {
  return statusError(Code.Internal, message);
}

/** Creates an invalid-argument status. */
export function invalidArgument(message, cause) {
  return statusError(Code.InvalidArgument, message, {}, cause);
}

/** Creates a failed-precondition status. */
export function failedPrecondition(message) {
  return statusError(Code.FailedPrecondition, message);
}

/**
 * The stream error code that resets the streams of a call the client abandons, on WebTransport and
 * QMux alike, as the Go and Rust clients do. Servers end a call whose request stream the client
 * reset as Cancelled.
 */
export const CancelledStreamErrorCode = 1;

/**
 * The reason to abort or cancel a stream of an abandoned call with, so that the transport resets
 * it with CancelledStreamErrorCode. A WebTransport stream is reset with code 0 unless the reason is
 * a WebTransportError that carries a stream error code; where the runtime has no WebTransportError,
 * an error of the same shape stands in.
 */
export function cancelStreamReason(message) {
  if (typeof globalThis.WebTransportError === "function") {
    // Browsers take one WebTransportErrorInit dictionary; its source is always "stream".
    return new globalThis.WebTransportError({ message, streamErrorCode: CancelledStreamErrorCode });
  }
  const error = new Error(message);
  error.name = "WebTransportError";
  return Object.assign(error, { source: "stream", streamErrorCode: CancelledStreamErrorCode });
}

/** Creates a deadline-exceeded status. */
export function deadlineExceeded(message) {
  return statusError(Code.DeadlineExceeded, message);
}

/** Creates an unavailable status. */
export function unavailable(message, cause) {
  return statusError(Code.Unavailable, message, {}, cause);
}

/** Creates a resource-exhausted status. */
export function resourceExhausted(message) {
  return statusError(Code.ResourceExhausted, message);
}

/** Creates a cancelled status. */
export function cancelled(message, cause) {
  return statusError(Code.Cancelled, message, {}, cause);
}

/** Converts a transport failure into a status error; status errors pass through. */
export function statusFromTransportError(error) {
  if (error instanceof TrevRpcError) {
    return error;
  }
  if (error?.name === "AbortError") {
    return cancelled("transport closed locally", error);
  }
  return unavailable(`transport unavailable: ${error?.message ?? String(error)}`, error);
}
