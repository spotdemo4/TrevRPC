// Writes src/zstd-wasm.js, which exports the libzstd module as a base64 string, from the module
// Nix builds out of this directory. Embedding it in JavaScript lets the zstd entry point load it in
// any bundler and runtime without asset handling.
//
// TREVRPC_ZSTD_WASM names the libzstd.wasm to embed; the development shell and the Nix build set
// it. Without it an existing src/zstd-wasm.js is kept.
import { access, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const output = fileURLToPath(new URL("../src/zstd-wasm.js", import.meta.url));
const wasm = process.env.TREVRPC_ZSTD_WASM;

if (wasm) {
  const base64 = (await readFile(wasm)).toString("base64");
  await writeFile(
    output,
    `// Generated by zstd-wasm/embed.js from ${wasm.replace(/^.*\//, "")}; do not edit.\nexport default "${base64}";\n`,
  );
} else {
  await access(output).catch(() => {
    console.error(
      "zstd-wasm/embed.js: set TREVRPC_ZSTD_WASM to the libzstd.wasm of `nix build .#trevrpc-js.zstdWasm`, or use the development shell",
    );
    process.exit(1);
  });
}
