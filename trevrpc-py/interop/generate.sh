#!/usr/bin/env bash
# Regenerates the interop bindings in gen/ from interop/proto with protoc-gen-py and
# protoc-gen-trevrpc-py, the plugin's _options_pb.py, which is gen/trevrpc/options_pb.py, and the
# messages of the runtime's protovalidate tests in ../tests/gen from ../tests/proto. Given two
# directories, writes only the interop and the test bindings, there. Both plugins come from PATH, or
# from ../protoc-gen-trevrpc-py's uv environment without them.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
root=$here/../..
out=${1:-$here/gen}
tests_out=${2:-$here/../tests/gen}

if ! command -v protoc-gen-trevrpc-py >/dev/null; then
	PATH=$here/../protoc-gen-trevrpc-py/.venv/bin:$PATH
fi

# Only what the plugins write goes: the directory may hold other files.
rm -rf "$out" "$tests_out"
mkdir -p "$out" "$tests_out"
protoc \
	-I "$root/interop/proto" \
	-I "$root/proto" \
	--py_out="$out" \
	--trevrpc-py_out="$out" \
	interop.proto compressed.proto unreliable.proto validated.proto buf/validate/validate.proto \
	trevrpc/options.proto
protoc \
	-I "$here/../tests/proto" \
	-I "$root/interop/proto" \
	--py_out="$tests_out" \
	rules.proto buf/validate/validate.proto

# The headers name each plugin's version, which a release (bumper) or a dependency update (Renovate)
# changes without regenerating them, and the trevrpc-py-generated check would then fail. Leave it out.
find "$out" "$tests_out" -name '*.py' -print0 | while IFS= read -r -d '' file; do
	sed -E 's/^(# Generated by protoc-gen-[a-z-]+) v[^ ]+ (with parameter )/\1 \2/' "$file" >"$file.tmp"
	mv "$file.tmp" "$file"
done

if [ $# -eq 0 ]; then
	cp "$out/trevrpc/options_pb.py" "$here/../protoc-gen-trevrpc-py/src/protoc_gen_trevrpc_py/_options_pb.py"
fi
